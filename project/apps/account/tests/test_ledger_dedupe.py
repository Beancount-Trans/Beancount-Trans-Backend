TEMPLATE_DIR = Path(settings.BASE_DIR).parent / 'Beancount-Trans-Assets'
OFFICIAL_ACCOUNT_JSON = (
    Path(settings.BASE_DIR)
    / 'project/fixtures/official_templates/account.json'
)


@pytest.mark.skipif(
    not (TEMPLATE_DIR / 'main.bean').exists(),
    reason='Beancount-Trans-Assets 模板仓库不存在',
)
def test_git_template_overlap_is_resolved(user):
    """复现「注册写平台 open → 启用 Git 模板」场景，验证重复 open 被清除"""
    import json
    import re
    import shutil

    official_items = {
        item['account_path']
        for item in json.loads(OFFICIAL_ACCOUNT_JSON.read_text(encoding='utf-8'))['items']
    }

    # 1. 模拟注册：平台为官方模板全部账户写 open + 占位 note
    directives = []
    for account_path in sorted(official_items):
        directives.append(f'2000-01-01 open {account_path}\n')
        directives.append(f'2026-11-05 note {account_path} "平台创建账户"\n')
    _write(
        user, 'trans/collect.bean',
        '; Trans directory - Auto-generated includes\n'
        '; This file is automatically generated by the platform\n\n'
        + '\n'.join(directives),
    )

    # 2. 模拟启用 Git 模板：复制模板（跳过 trans/，trans/ 内容保留）
    root = _root(user)
    for item in TEMPLATE_DIR.iterdir():
        if item.name in ('trans', '.git'):
            continue
        target = root / item.name
        if item.is_dir():
            if target.exists():
                shutil.rmtree(target)
            shutil.copytree(item, target)
        else:
            shutil.copy2(item, target)

    # 3. 模板自身 open 与官方模板账户的重叠数量
    template_opens = set()
    for bean_file in (root / 'account').glob('*.bean'):
        for line in bean_file.read_text(encoding='utf-8').splitlines():
            match = re.match(r'^\d{4}-\d{2}-\d{2}\s+open\s+(\S+)', line.strip())
            if match:
                template_opens.add(match.group(1))
    overlap = official_items & template_opens
    assert overlap, '模板与官方账户模板无重叠，测试前提不成立'

    account_snapshot = {
        path.name: path.read_bytes()
        for path in (root / 'account').glob('*.bean')
    }

    result = dedupe_platform_opens(user)

    assert result.changed is True
    assert len(result.removed_opens) == len(overlap)
    assert not [
        message for message in _messages(_account_errors(user))
        if 'Duplicate open' in message
    ]
    # 模板文件保持原样
    for path in (root / 'account').glob('*.bean'):
        assert path.read_bytes() == account_snapshot[path.name]

