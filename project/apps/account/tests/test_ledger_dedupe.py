"""平台账本 open 去重测试

覆盖：
- 平台 collect.bean 与模板 account/*.bean 重复 open → 只删平台那份
- 幂等：重复执行不再改动
- 占位 note 早于外部 open → 日期改写为外部 open 日期
- 未被 main.bean include 的文件不参与判断
- main.bean 缺失时按全部 .bean 兜底
- 不修改用户/模板文件
- 平台状态 note 原样保留

所有测试将 settings.ASSETS_BASE_PATH 指向 tmp_path，避免污染真实 Assets 目录。
"""
import os
from pathlib import Path

import pytest
from django.conf import settings
from django.contrib.auth import get_user_model

from project.apps.account.ledger_dedupe import (
    dedupe_platform_opens,
    resolve_effective_files,
)
from project.utils.file import BeanFileManager

User = get_user_model()

pytestmark = pytest.mark.django_db

ACCOUNT_A = 'Assets:Savings:DedupeA'
ACCOUNT_B = 'Assets:Savings:DedupeB'
ACCOUNT_C = 'Assets:Savings:DedupeC'


@pytest.fixture
def assets_dir(tmp_path, monkeypatch):
    base = tmp_path / 'Assets'
    base.mkdir()
    monkeypatch.setattr(settings, 'ASSETS_BASE_PATH', str(base))
    return base


@pytest.fixture
def user(assets_dir):
    return User.objects.create_user(username='dedupeuser', password='testpass123')


def _root(user):
    return Path(BeanFileManager.get_user_assets_path(user))


def _write(user, relative_path, content):
    path = _root(user) / relative_path
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding='utf-8')
    return path


def _write_main(user, includes):
    lines = ['; test main']
    lines.extend(f'include "{item}"' for item in includes)
    return _write(user, 'main.bean', '\n'.join(lines) + '\n')


def _collect_text(user):
    return Path(BeanFileManager.get_collect_bean_path(user)).read_text(encoding='utf-8')


def _account_errors(user):
    from beancount import loader

    main_path = BeanFileManager.get_main_bean_path(user)
    if not os.path.isfile(main_path):
        return []
    _entries, errors, _options = loader.load_file(main_path)
    return errors


def _messages(errors):
    return [str(getattr(error, 'message', '') or '') for error in errors]


def test_dedupe_removes_platform_open_keeps_user_file(user):
    _write_main(user, ['account/assets.bean', 'trans/main.bean'])
    _write(user, 'trans/collect.bean', (
        '; Trans directory - Auto-generated includes\n'
        '; This file is automatically generated by the platform\n\n'
        f'2000-01-01 open {ACCOUNT_A}\n\n'
        f'2000-01-01 open {ACCOUNT_B}\n'
    ))
    account_path = _write(user, 'account/assets.bean', (
        f'2015-01-01 open {ACCOUNT_A} CNY\n'
        f'2015-01-01 open {ACCOUNT_C} CNY\n'
    ))
    account_before = account_path.read_bytes()

    # include 图能解析到嵌套的 trans/collect.bean
    effective = resolve_effective_files(BeanFileManager.get_main_bean_path(user))
    assert BeanFileManager.get_collect_bean_path(user) in effective

    result = dedupe_platform_opens(user)

    assert result.changed is True
    assert result.removed_opens == [f'2000-01-01 open {ACCOUNT_A}']
    text = _collect_text(user)
    assert f'open {ACCOUNT_A}' not in text
    assert f'open {ACCOUNT_B}' in text

    # 用户/模板文件不被修改
    assert account_path.read_bytes() == account_before

    assert not [
        message for message in _messages(_account_errors(user))
        if 'Duplicate open' in message
    ]


def test_dedupe_is_idempotent(user):
    _write_main(user, ['account/assets.bean', 'trans/main.bean'])
    _write(user, 'trans/collect.bean', f'2000-01-01 open {ACCOUNT_A}\n')
    _write(user, 'account/assets.bean', f'2015-01-01 open {ACCOUNT_A} CNY\n')

    first = dedupe_platform_opens(user)
    assert first.changed is True
    text_after_first = _collect_text(user)

    second = dedupe_platform_opens(user)
    assert second.changed is False
    assert second.removed_opens == []
    assert _collect_text(user) == text_after_first


def test_placeholder_note_moves_after_external_open(user):
    _write_main(user, ['account/assets.bean', 'trans/main.bean'])
    _write(user, 'trans/collect.bean', (
        f'2000-01-01 open {ACCOUNT_A}\n\n'
        f'2026-11-05 note {ACCOUNT_A} "平台创建账户"\n'
    ))
    _write(user, 'account/assets.bean', f'2027-01-01 open {ACCOUNT_A} CNY\n')

    result = dedupe_platform_opens(user)

    assert result.changed is True
    assert result.rewritten_notes == [
        f'2027-01-01 note {ACCOUNT_A} "平台创建账户"'
    ]
    text = _collect_text(user)
    assert f'2027-01-01 note {ACCOUNT_A} "平台创建账户"' in text
    assert f'2026-11-05 note {ACCOUNT_A}' not in text
    assert not [
        message for message in _messages(_account_errors(user))
        if 'Invalid reference' in message
    ]


def test_non_effective_file_does_not_trigger_dedupe(user):
    _write_main(user, ['account/assets.bean', 'trans/main.bean'])
